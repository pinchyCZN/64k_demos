"""Check every doc cross-reference resolves - from docs/ AND from src/.

A ref in docs/ is relative to the DEMO ROOT - docs/<demo>/ - or to
docs/ for the shared files at the top. That convention is what let the
restructure keep them unedited; see docs/layout.txt section 4.

src/ FOLLOWS THE SAME CONVENTION, with the demo taken from the source
file's own directory: subsystems/raster.txt written in src/lithium/
is docs/lithium/subsystems/raster.txt, and a file directly in src/ is
rooted at docs/. Two other forms appear in src/ and both resolve - a
docs/-rooted path read from the repo root, and a bare filename, which
is looked up by name in that demo's tree and then in the shared docs.

A BARE FILENAME CAN BE AMBIGUOUS AND THAT IS WORTH REPORTING: ukko
has both subsystems/music.txt and formats/music.txt, so a bare
music.txt there names two different documents and the reader cannot
tell which.

    py -3.10 tools/checkrefs.py        from the repo root
"""
import io
import os
import re
import sys

# docs/: only a ref carrying one of the four section directories.
DOC_PAT = re.compile(r'(?<![\w/.])((?:\.\./)*'
                     r'(?:effects|subsystems|formats|structs)/[a-z0-9_]+\.txt)')

# src/: the same, plus docs/-rooted paths and bare filenames. The
# lookbehind keeps a runtime filename the code builds - .crash.txt,
# agent.crash.txt - from reading as a reference.
SRC_PAT = re.compile(r'(?<![\w/.-])((?:\.\./)*(?:[a-z0-9_]+/)*'
                     r'[a-z0-9_]+\.txt)')

# Generated by tools/export_maps.py into reverse/exports/, which is
# gitignored - named legitimately, absent on a fresh clone.
GENERATED = ('function_map.txt', 'symbol_map.txt', 'struct_map.txt')


def doc_index():
    """basename -> every docs/ path carrying it."""
    out = {}
    for root, _, files in os.walk('docs'):
        for f in files:
            if f.endswith('.txt'):
                out.setdefault(f, []).append(
                    os.path.join(root, f).replace(os.sep, '/'))
    return out


def demo_root(path):
    parts = path.split('/')
    if len(parts) > 2 and os.path.isdir('docs/' + parts[1]):
        return 'docs/' + parts[1]
    return 'docs'


def resolve_src(path, ref, index):
    """Candidate targets: exactly one is a pass, none or many is not."""
    if os.path.basename(ref) in GENERATED:
        return ['generated']
    if ref.startswith('docs/'):
        return [os.path.normpath(ref).replace(os.sep, '/')]
    if ref.startswith('../'):
        t = os.path.normpath(os.path.join(os.path.dirname(path), ref))
        return [t.replace(os.sep, '/')]
    if '/' in ref:
        t = os.path.normpath(os.path.join(demo_root(path), ref))
        return [t.replace(os.sep, '/')]
    hits = [h for h in index.get(ref, [])
            if h.startswith(demo_root(path) + '/') or h.count('/') == 1]
    return hits


def check_docs():
    bad, tot = [], 0
    for root, _, files in os.walk('docs'):
        for f in files:
            if not f.endswith('.txt'):
                continue
            p = os.path.join(root, f).replace(os.sep, '/')
            parts = p.split('/')
            base = '/'.join(parts[:2]) if len(parts) > 2 else 'docs'
            s = io.open(p, encoding='ascii').read()
            for m in DOC_PAT.finditer(s):
                tot += 1
                r = m.group(1)
                if r.startswith('../'):
                    t = os.path.normpath(os.path.join(root, r))
                else:
                    t = os.path.normpath(os.path.join(base, r))
                if not os.path.exists(t):
                    bad.append((p, r, t.replace(os.sep, '/')))
    return tot, bad


def check_src():
    index = doc_index()
    bad, tot = [], 0
    for root, dirs, files in os.walk('src'):
        dirs[:] = [d for d in dirs if d != 'third_party']
        for f in sorted(files):
            if not f.endswith(('.c', '.h')):
                continue
            p = os.path.join(root, f).replace(os.sep, '/')
            with io.open(p, encoding='utf-8', errors='replace') as fh:
                for n, line in enumerate(fh, 1):
                    for m in SRC_PAT.finditer(line):
                        tot += 1
                        r = m.group(1)
                        hits = resolve_src(p, r, index)
                        where = '%s:%d' % (p, n)
                        if len(hits) == 1:
                            if (hits[0] == 'generated'
                                    or os.path.exists(hits[0])):
                                continue
                            bad.append((where, r, hits[0]))
                        elif not hits:
                            bad.append((where, r, 'no such document'))
                        else:
                            bad.append((where, r,
                                        'ambiguous - ' + ', '.join(hits)))
    return tot, bad


def main():
    dt, db = check_docs()
    st, sb = check_src()
    print('%d refs in docs/, %d unresolved' % (dt, len(db)))
    print('%d refs in src/,  %d unresolved' % (st, len(sb)))
    for p, r, t in db + sb:
        print('   %-38s %-30s -> %s' % (p, r, t))
    return 1 if (db or sb) else 0


if __name__ == '__main__':
    sys.exit(main())
